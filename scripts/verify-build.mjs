import {readFileSync,statSync} from 'node:fs';
import assert from 'node:assert/strict';
const html=readFileSync('dist/index.html','utf8');
assert.ok(!html.includes('/src/'),'Production HTML references source');
for(const [,url] of html.matchAll(/(?:src|href)="(\.\/assets\/[^\"]+)"/g))assert.ok(statSync(`dist/${url}`).size>0);
const asset=JSON.parse(readFileSync('src/showroom/model-asset.json','utf8'));
const bytes=readFileSync(`dist/${asset.path}`);assert.equal(bytes.length,asset.bytes);assert.equal(bytes.toString('utf8',0,4),'glTF');
const manifest=JSON.parse(readFileSync('dist/models/manifest.json','utf8'));assert.equal(manifest.vehicles[0].glb,asset.path);
assert.ok(statSync('dist/models/showroom-architecture.json').size>0);
console.log('Production entry, bundled assets, compressed model and architecture manifest verified.');
